    fun getById(id: Int): Recipe? {
        for (recipe in all) {
            if (recipe.id == id) {
                return recipe
            }
        }
        return null
    }

    fun getByCategory(category: String): List<Recipe> {
        val result = ArrayList<Recipe>()
        for (recipe in all) {
            if (recipe.category == category) {
                result.add(recipe)
            }
        }
        return result
    }

    fun search(query: String): List<Recipe> {
        val q = query.trim().lowercase()
        val result = ArrayList<Recipe>()
        for (recipe in all) {
            var found = recipe.title.lowercase().contains(q)
            for (ingredient in recipe.ingredients) {
                if (ingredient.name.lowercase().contains(q)) {
                    found = true
                }
            }
            if (found) {
                result.add(recipe)
            }
        }
        return result
    }

    fun getFavorites(context: Context): List<Recipe> {
        val ids = Favorites.getIds(context)
        val result = ArrayList<Recipe>()
        for (recipe in all) {
            if (ids.contains(recipe.id.toString())) {
                result.add(recipe)
            }
        }
        return result
    }

